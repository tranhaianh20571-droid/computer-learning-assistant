import assert from "node:assert/strict";
import {TeachingBuffer} from "../frontend/src/lib/teachingBuffer.ts";
const buffer=new TeachingBuffer();
const first={text:"甲乙丙丁戊己庚辛壬癸",active:true,final:false,board:{presentation:{blocks:[{id:"a",type:"text",text:"关键内容"}]}},beats:[{id:"b",text:"甲乙丙丁戊己庚辛壬癸",block_ids:["a"]}]};
buffer.receive("step:1",first);buffer.advance(50);
const shown=buffer.view("step:1");
buffer.setPaused(true);
buffer.receive("step:1",{...first,text:first.text+"继续补充知识",final:true});
buffer.advance(500);
assert.deepEqual(buffer.view("step:1"),shown);
buffer.receive("step:2",{...first,active:false,final:true});
assert.equal(buffer.view("step:2").text,"");
buffer.setPaused(false);buffer.advance(100);
assert(buffer.view("step:1").text.length>shown.text.length);
buffer.receive("step:2",{...first,active:true,final:true});
assert.equal(buffer.view("step:2").text.length,1);
buffer.setPaused(true);
buffer.receive("followup:2",{text:"合成追问回答",active:true,followup:true,final:true});
buffer.advance(100);
assert.equal(buffer.view("followup:2").text.length,0);
buffer.setPaused(false);buffer.advance(100);
assert(buffer.view("followup:2").text.length>0);
buffer.setPaused(true);
const pausedAnswer=buffer.view("followup:2");
buffer.receive("followup:2",{text:"合成追问回答继续补充",active:true,followup:true,final:true});
buffer.advance(3000);
assert.deepEqual(buffer.view("followup:2"),pausedAnswer);
console.log("Pause freezes lesson and followup, including late publication; explicit resume passed");
