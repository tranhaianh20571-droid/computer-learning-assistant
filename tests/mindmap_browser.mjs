const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const guest = await context.request.get(`${backend}/api/auth/guest`);
const user = await guest.json();
const seed = spawnSync(process.env.TEST_PYTHON, ["tests/course_library_browser_fixture.py", user.user_id], { env: process.env, encoding: "utf8" });
