import assert from "node:assert/strict";
import {TeachingBuffer} from "../frontend/src/lib/teachingBuffer.ts";
import {layoutBoard} from "../frontend/src/lib/boardLayout.ts";
import {presentBoard,stableElements} from "../frontend/src/lib/boardPresentation.ts";
import {audioCharacters} from "../frontend/src/lib/audioTiming.ts";
const buffer=new TeachingBuffer();buffer.receive('step:1',{text:'甲'.repeat(300),active:true,final:true});
for(let n=0;n<60;n++)buffer.advance(1000/60);
assert(buffer.view('step:1').shown<=13);assert(buffer.view('step:1').remaining>280);
buffer.audioClock('step:1',20);buffer.advance(16);assert.equal(buffer.view('step:1').shown,20);
buffer.audioClock('step:1',3);buffer.advance(16);assert.equal(buffer.view('step:1').shown,20);
buffer.setPaused(true);buffer.audioClock('step:1',200);buffer.advance(16);assert.equal(buffer.view('step:1').shown,20);
const text={id:'text',type:'text',text:'文字解释。'.repeat(15)},table={id:'table',type:'table',columns:['关系','说明'],rows:[['甲','乙']]};
const geometry=layoutBoard([text,table],1000,new Set(['text','table']),[],{},'',{},{});
const before=JSON.stringify(geometry.pages[0].placements);
const first=presentBoard(geometry.pages[0],[{...text,text:'文'}]);
const second=presentBoard(geometry.pages[0],[{...text,text:'文字'}]);
assert.equal(JSON.stringify(geometry.pages[0].placements),before);
const cache=new Map();let restored=0;
const restore=raw=>{restored+=raw.length;return raw.map(element=>({...element,version:element.version||1,seed:100}));};
const a=stableElements(first,cache,restore),count=restored;
assert.deepEqual(stableElements(first,cache,restore),a);assert.equal(restored,count);
const b=stableElements(second,cache,restore);assert.equal(restored-count,1);
assert(a.filter(e=>!e.customData?.bodyText).every(e=>b.includes(e)));
assert.equal(audioCharacters('甲乙丙丁',[{text:'甲乙',begin_ms:0,end_ms:1000},{text:'丙丁',begin_ms:1000,end_ms:2000}],1500),3);
const gated=new TeachingBuffer();gated.receive('step:audio',{text:'等待语音后显示',active:true,final:true,revealReady:false});
for(let n=0;n<30;n++)gated.advance(1000/60);
assert.equal(gated.view('step:audio').shown,0);
gated.audioGate('step:audio',false);gated.audioClock('step:audio',4);gated.advance(16);
assert.equal(gated.view('step:audio').shown,4);
console.log('Slow buffered output, pause/audio monotonic cursor, immutable geometry and one-element update passed');
